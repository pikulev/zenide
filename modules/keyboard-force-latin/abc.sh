#!/usr/bin/env sh
# Форс латинской раскладки (ABC). Зовётся из tmux-хуков на ЛЮБОЙ переход
# (окно/пейн/сессия) — чтобы хоткеи hx/yazi/lazygit/… всегда работали, не
# завися от того, что осталась включена кириллица. Русский в этих окнах нужен
# редко → переключаешь руками (форс только на переходе, внутри окна не мешает).
# macism меняет input source фронт-приложения (ghostty). Тихо и быстро.
m="$(command -v macism 2>/dev/null || echo /opt/homebrew/bin/macism)"
[ -x "$m" ] && "$m" com.apple.keylayout.ABC >/dev/null 2>&1
exit 0
