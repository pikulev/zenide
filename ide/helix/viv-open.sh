#!/bin/sh
# Открыть файл в vivify (hx Space m). Единственная причина существования:
# %{buffer_name} для файлов вне cwd приходит со схлопнутым домом («~/…»),
# а тильда в кавычках шеллом не разворачивается — viv получал литеральный «~».
#
# Перезагрузки превью на каждое сохранение глушатся на стороне страницы —
# см. config/vivify/soft-reload.js.

f="$1"
case "$f" in
    "~/"*) f="$HOME/${f#"~/"}" ;;
esac
exec viv "$f"
