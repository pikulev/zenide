# mise: рантаймы (node/pnpm/bun) и языковые CLI (LSP, prettier, ruff, ty).
# Что именно стоит — ide/mise/config.toml → ~/.config/mise/config.toml.
#
# Две строки активации делают РАЗНОЕ, и нужны обе:
#
#   --shims   кладёт на PATH каталог шимов (~/.local/share/mise/shims).
#             Статичный путь, поэтому его видят процессы, которые не проходят
#             через интерактивный шелл: попапы tmux, GUI, `bash tests/*.sh`.
#   activate  подменяет PATH каталогами нужной версии и ставит хуки на cd —
#             переключение версии по каталогу работает только так.
#             Только интерактивный шелл.
#
# Без первой строки `command -v prettier` внутри tmux-попапа молча не находит
# тул (PATH в попапах не гарантирован — см. AGENTS.md): попап деградирует до
# «без подсветки», а zenide doctor при этом зелёный, потому что из своего
# шелла всё видно. Невоспроизводимый баг на ровном месте.
#
# GUI-приложениям, запущенным не из шелла, не видно и шимов — если такое
# понадобится, строку с --shims надо продублировать в ~/.zprofile.
#
# Гард на свежую машину: до `brew bundle` mise ещё нет, шелл не должен падать.
if command -v mise >/dev/null 2>&1; then
    eval "$(mise activate zsh --shims)"
    eval "$(mise activate zsh)"
fi
