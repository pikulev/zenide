# gitui — TUI-клиент git.
#
# GIT_EDITOR=hx, и это осознанно НЕ мост в работающий hx. У gitui одна ручка на
# два разных дела: открыть файл и отредактировать сообщение коммита. Мост
# (`zenide open`) возвращает управление сразу — и сообщение коммита gitui
# прочитал бы ПУСТЫМ, потому что читает файл сразу после выхода редактора.
# Блокирующий hx корректен в обоих случаях.
#
# GIT_EDITOR имеет наивысший приоритет в gitui (GIT_EDITOR > core.editor >
# VISUAL > EDITOR), поэтому действует только на процесс gitui.
gitui() {
    GIT_EDITOR=hx command gitui "$@"
}
